#!/bin/bash
# Derives the iOS version from git and writes app/ios/Version.xcconfig.
#
# It has to be an xcconfig rather than a build-phase edit of the built Info.plist:
# Xcode 26+ writes that plist as the very last step of the build, after every script
# phase, so a script that patches it is silently overwritten. CFBundleShortVersionString
# and CFBundleVersion come from MARKETING_VERSION and CURRENT_PROJECT_VERSION, which are
# build settings, so they must be set before the build starts.
#
# Run before `xcodegen generate` / `xcodebuild`. scripts/ios.sh and the CI workflows
# both do; the Xcode pre-build script refuses a Release archive whose version is stale.
set -euo pipefail

cd "$(dirname "$0")/.."

TAG=$(git describe --tags --abbrev=0 --match 'v[0-9]*' 2>/dev/null || true)

# App Store Connect accepts only 1–3 dot-separated integers in CFBundleShortVersionString,
# so a pre-release tag (v1.1.0-alpha01) has to lose its suffix or the upload is rejected.
VERSION_NAME=$(printf '%s' "${TAG#v}" | sed -E 's/[-+].*$//')
if ! printf '%s' "$VERSION_NAME" | grep -qE '^[0-9]+(\.[0-9]+){0,2}$'; then
    echo "warning: no store-safe version in tag '${TAG:-<none>}'; using 1.0.0" >&2
    VERSION_NAME="1.0.0"
fi

# Commit count: monotonic, and already what the Android build uses. CI must clone with
# fetch-depth 0 — a shallow clone would hand App Store Connect a lower build number.
BUILD_NUMBER=$(git rev-list --count HEAD 2>/dev/null || echo "1")

cat > app/ios/Version.xcconfig <<EOF
// Generated by scripts/ios-version.sh — do not edit, do not commit.
// Source tag: ${TAG:-<none>}
MARKETING_VERSION = $VERSION_NAME
CURRENT_PROJECT_VERSION = $BUILD_NUMBER
EOF

echo "$VERSION_NAME ($BUILD_NUMBER)"
